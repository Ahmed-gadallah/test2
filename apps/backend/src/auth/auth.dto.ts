import { ApiProperty } from '@nestjs/swagger';
import { IsIn, IsJWT, IsNotEmpty, IsString, Length, Matches, MaxLength, MinLength } from 'class-validator';

export class MobileDto {
  @ApiProperty({ example: '0500000001', description: 'Saudi mobile in any common format' })
  @IsString()
  @IsNotEmpty()
  @MaxLength(32)
  mobile: string;
}

export class SendOtpDto extends MobileDto {
  @ApiProperty({ enum: ['register', 'reset_password'] })
  @IsIn(['register', 'reset_password'])
  purpose: 'register' | 'reset_password';
}

export class VerifyOtpDto extends SendOtpDto {
  @ApiProperty({ example: '123456' })
  @Matches(/^\d{6}$/)
  code: string;
}

export class DeviceDto {
  @ApiProperty({ description: 'Stable per-install identifier generated by the app' })
  @IsString()
  @Length(8, 128)
  deviceId: string;

  @ApiProperty({ enum: ['android', 'ios', 'web'] })
  @IsIn(['android', 'ios', 'web'])
  platform: 'android' | 'ios' | 'web';
}

const PASSWORD_RULE = /^(?=.*[A-Za-z؀-ۿ])(?=.*\d).{8,128}$/;

export class RegisterDto extends DeviceDto {
  @ApiProperty()
  @IsJWT()
  verificationToken: string;

  @ApiProperty({ description: '8–128 chars, at least one letter and one digit' })
  @Matches(PASSWORD_RULE, { message: 'Password must be 8-128 characters and include a letter and a digit' })
  password: string;

  @ApiProperty({ enum: ['ar', 'en'], required: false })
  @IsIn(['ar', 'en'])
  language: 'ar' | 'en' = 'ar';
}

export class LoginDto extends DeviceDto {
  @ApiProperty({ example: '0500000001' })
  @IsString()
  @MaxLength(32)
  mobile: string;

  @ApiProperty()
  @IsString()
  @MinLength(1)
  @MaxLength(128)
  password: string;
}

export class RefreshDto {
  @ApiProperty()
  @IsString()
  @Length(20, 300)
  refreshToken: string;
}

export class ResetPasswordDto {
  @ApiProperty()
  @IsJWT()
  verificationToken: string;

  @ApiProperty()
  @Matches(PASSWORD_RULE, { message: 'Password must be 8-128 characters and include a letter and a digit' })
  password: string;
}
